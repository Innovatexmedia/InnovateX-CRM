// Service-role client, lazily created. Needed to see whether another
// account already owns this phone number — RLS hides other accounts'
// rows from the caller's own session. Same pattern as
// /api/whatsapp/config.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
let _adminClient: any = null
function supabaseAdmin() {
  if (!_adminClient) {
    _adminClient = createAdminClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!,
      process.env.SUPABASE_SERVICE_ROLE_KEY!,
    )
  }
  return _adminClient
}

/** Same `{ error, meta }` shape the manual connect route answers, so the
 *  settings page shows Meta failures the same way for both flows. */
function metaFailure(err: unknown, step: MetaConnectStep, ctx: MetaErrorContext) {
  const explained = explainMetaError(err, step, ctx)
  console.error(`[whatsapp/embedded-signup] Meta ${step} failed:`, explained.metaMessage, {
    code: explained.code,
    subcode: explained.subcode,
    fbtrace_id: explained.fbtraceId,
  })
  return NextResponse.json(
    { error: explained.summary, meta: metaErrorPayload(explained) },
    { status: explained.httpStatus },
  )
}

/**
 * POST /api/whatsapp/embedded-signup
 *
 * Finishes the "Connect with Facebook" flow. The settings page runs
 * Meta's Embedded Signup popup and posts what it got back:
 *
 *   { code, phone_number_id, waba_id, business_id?, event? }
 *
 * Then, on the server (the App Secret never leaves it):
 *   1. exchange `code` for the customer's business access token,
 *   2. prove the number really lives under that WABA,
 *   3. register the number with the Cloud API (PIN generated by us,
 *      stored encrypted) — skipped for WhatsApp Business app numbers,
 *   4. subscribe the WABA to our app so webhooks are delivered,
 *   5. save the encrypted token + ids on the account's `whatsapp_config`.
 *
 * Admin or owner only. Answers like POST /api/whatsapp/config:
 *   200 { success: true, registered, registration_skipped, phone_info }
 *   200 { success: false, saved: true, registered: false, registration_error }
 *   400/502 { error, meta? }   — nothing saved
 *   503 { error, code: 'not_configured' }
 */
export async function POST(request: Request) {
  try {
    const { supabase, userId, accountId } = await requireRole('admin')

    const limit = checkRateLimit(`embedded-signup:${userId}`, { limit: 6, windowMs: 60_000 })
    if (!limit.success) return rateLimitResponse(limit)

    const env = getEmbeddedSignupServerEnv()
    if (!env) {
      return NextResponse.json(
        {
          error:
            'Connect with Facebook is not set up on this server yet. Use "Connect manually", or ask the administrator to configure Embedded Signup.',
          code: 'not_configured',
        },
        { status: 503 },
      )
    }

    const parsed = parseEmbeddedSignupRequest(await request.json().catch(() => null))
    if (!parsed.ok) {
      return NextResponse.json({ error: parsed.error, field: parsed.field }, { status: 400 })
    }
    const { code, phoneNumberId, wabaId, event } = parsed.value
    const metaCtx: MetaErrorContext = { phoneNumberId, wabaId }

    // Check ownership BEFORE spending the one-time code: a number can be
    // linked to one account only (a second claim would make the webhook's
    // phone_number_id lookup ambiguous and drop every inbound message).
    const { data: claimed, error: claimedError } = await supabaseAdmin()
      .from('whatsapp_config')
      .select('account_id')
      .eq('phone_number_id', phoneNumberId)
      .neq('account_id', accountId)
      .maybeSingle()
    if (claimedError) {
      console.error('[whatsapp/embedded-signup] ownership check failed:', claimedError)
      return NextResponse.json({ error: 'Failed to validate configuration' }, { status: 500 })
    }
    if (claimed) {
      return NextResponse.json(
        {
          error:
            'This WhatsApp phone number is already linked to another account on this instance. Each phone number can only be connected to one InnovateX CRM user.',
        },
        { status: 409 },
      )
    }

    // 1. code → business token. The code lives ~30 s and works once, so a
    //    failure here nearly always means "click Connect with Facebook again".
    let accessToken: string
    try {
      const exchanged = await exchangeEmbeddedSignupCode({
        appId: env.appId,
        appSecret: env.appSecret,
        code,
      })
      accessToken = exchanged.accessToken
    } catch (err) {
      const e = err instanceof MetaApiError ? err : null
      console.error(
        '[whatsapp/embedded-signup] code exchange failed:',
        err instanceof Error ? err.message : err,
        { code: e?.code, subcode: e?.subcode, fbtrace_id: e?.fbtraceId },
      )
      return NextResponse.json(
        {
          error:
            'Facebook login expired or was already used. Please click "Connect with Facebook" and complete the popup again.',
          meta: {
            code: e?.code ?? null,
            subcode: e?.subcode ?? null,
            fbtrace_id: e?.fbtraceId ?? null,
            step: 'exchange_code',
            field: null,
            message: describeMetaError(err, 'Code exchange failed'),
          },
        },
        { status: 400 },
      )
    }

    // 2. The number resolves with this token AND lives under this WABA.
    let phoneInfo
    try {
      phoneInfo = await verifyPhoneNumber({ phoneNumberId, accessToken })
    } catch (err) {
      return metaFailure(err, 'verify_number', metaCtx)
    }

    let wabaNumbers
    try {
      wabaNumbers = await listWabaPhoneNumbers({ wabaId, accessToken })
    } catch (err) {
      return metaFailure(err, 'waba_phone_numbers', metaCtx)
    }
    if (!phoneNumberBelongsToWaba(wabaNumbers, phoneNumberId)) {
      return NextResponse.json(
        {
          error: describeWabaPhoneMismatch(wabaNumbers, phoneNumberId, wabaId),
          field: 'waba_id',
          meta: {
            code: null,
            subcode: null,
            fbtrace_id: null,
            step: 'waba_phone_numbers',
            field: 'waba_id',
            message: 'phone_number_id is not listed under waba_id',
          },
        },
        { status: 400 },
      )
    }

    // Encrypt the token up front so a bad ENCRYPTION_KEY fails before we
    // change anything on Meta's side.
    let encryptedAccessToken: string
    try {
      encryptedAccessToken = encrypt(accessToken)
    } catch (err) {
      console.error('[whatsapp/embedded-signup] encryption failed:', err)
      return NextResponse.json(
        {
          error:
            'Failed to encrypt token. Check that ENCRYPTION_KEY is a valid 64-character hex string in your environment variables.',
        },
        { status: 500 },
      )
    }

    // 3. Register for inbound webhooks. Reconnecting the same number
    //    reuses the PIN we stored last time; a new number gets a fresh one.
    const { data: existing } = await supabase
      .from('whatsapp_config')
      .select('id, phone_number_id, registered_at, two_step_pin')
      .eq('account_id', accountId)
      .maybeSingle()

    const skipRegister = SKIP_REGISTER_EVENTS.has(event)
    let pinUsed: string | null = null
    let registeredAt: string | null = null
    let registrationError: string | null = null
    let registrationMeta: ReturnType<typeof metaErrorPayload> | null = null

    if (skipRegister) {
      // WhatsApp Business app number (coexistence): Meta has already
      // brought it live — /register would fail and isn't needed.
      registeredAt = new Date().toISOString()
    } else {
      if (existing?.phone_number_id === phoneNumberId && existing.two_step_pin) {
        try {
          pinUsed = decrypt(existing.two_step_pin as string)
        } catch {
          pinUsed = null // unreadable (e.g. key rotated) — generate a new one
        }
      }
      pinUsed = pinUsed ?? generateRegistrationPin()

      try {
        await registerPhoneNumber({ phoneNumberId, accessToken, pin: pinUsed })
        registeredAt = new Date().toISOString()
      } catch (err) {
        const explained = explainMetaError(err, 'register', metaCtx)
        registrationError = explained.summary
        registrationMeta = metaErrorPayload(explained)
        console.error(
          '[whatsapp/embedded-signup] /register failed:',
          explained.metaMessage,
          registrationMeta,
        )
        // Fall through and still save, so the failure is visible in
        // Settings (same behaviour as the manual form).
      }
    }

    // 4. Subscribe the WABA to this app. Without it Meta delivers nothing,
    //    so a failure here aborts the connect (nothing has been saved).
    let subscribedAppsAt: string
    try {
      await subscribeWabaToApp({ wabaId, accessToken })
      subscribedAppsAt = new Date().toISOString()
    } catch (err) {
      return metaFailure(err, 'subscribe_waba', metaCtx)
    }

    // 5. Save.
    const now = new Date().toISOString()
    const baseRow: Record<string, unknown> = {
      phone_number_id: phoneNumberId,
      waba_id: wabaId,
      access_token: encryptedAccessToken,
      status: registrationError ? 'disconnected' : 'connected',
      connected_at: registrationError ? null : now,
      registered_at: registrationError ? null : registeredAt,
      subscribed_apps_at: subscribedAppsAt,
      last_registration_error: registrationError,
      // The popup ran under OUR Tech Provider app, so that is the app the
      // WABA is subscribed to — the "Test API Connection" check and media
      // header uploads compare/use this id.
      app_id: env.appId,
      connected_via: 'embedded_signup',
      updated_at: now,
    }
    if (pinUsed) {
      try {
        baseRow.two_step_pin = encrypt(pinUsed)
      } catch (err) {
        console.error('[whatsapp/embedded-signup] PIN encryption failed:', err)
      }
    }

    if (existing) {
      const { error: updateError } = await supabase
        .from('whatsapp_config')
        .update(baseRow)
        .eq('account_id', accountId)
      if (updateError) {
        console.error('[whatsapp/embedded-signup] update failed:', updateError)
        return NextResponse.json({ error: 'Failed to update configuration' }, { status: 500 })
      }
    } else {
      const { error: insertError } = await supabase
        .from('whatsapp_config')
        .insert({ account_id: accountId, user_id: userId, ...baseRow })
      if (insertError) {
        console.error('[whatsapp/embedded-signup] insert failed:', insertError)
        return NextResponse.json({ error: 'Failed to save configuration' }, { status: 500 })
      }
    }

    if (registrationError) {
      return NextResponse.json({
        success: false,
        saved: true,
        registered: false,
        registration_error: registrationError,
        error: registrationError,
        meta: registrationMeta,
        phone_info: phoneInfo,
      })
    }

    return NextResponse.json({
      success: true,
      saved: true,
      registered: true,
      registration_skipped: skipRegister,
      phone_info: phoneInfo,
    })
  } catch (error) {
    // requireRole throws Unauthorized/Forbidden; toErrorResponse maps
    // those to 401/403 and collapses anything else to a generic 500.
    console.error('Error in WhatsApp embedded-signup POST:', error)
    return toErrorResponse(error)
  }
}